import { useState } from 'react'
import { Sparkles, AlertCircle, Copy, Check, Download, ThumbsUp, ThumbsDown, Share2 } from 'lucide-react'
import ConfidenceBadge from './ConfidenceBadge'
import SourceCard from './SourceCard'
import EscalationAlert from './EscalationAlert'

// Parse markdown-ish text to simple JSX
function parseAnswer(text) {
  if (!text) return null
  return text.split('\n').map((line, i) => {
    if (line.startsWith('**') && line.endsWith('**')) {
      return <p key={i} className="font-semibold text-white mt-3 mb-1">{line.replace(/\*\*/g, '')}</p>
    }
    if (line.startsWith('• ') || line.startsWith('- ')) {
      return (
        <li key={i} className="text-slate-300 text-sm leading-relaxed ml-4 list-disc">
          {line.replace(/^[•\-]\s*/, '').replace(/\*\*(.*?)\*\*/g, (_, m) => m)}
        </li>
      )
    }
    if (line.startsWith('# ') || line.startsWith('## ') || line.startsWith('### ')) {
      return <p key={i} className="font-semibold text-slate-200 mt-3 mb-1 text-sm">{line.replace(/^#+\s*/, '')}</p>
    }
    if (line.trim() === '---') {
      return <hr key={i} className="border-white/5 my-3" />
    }
    if (!line.trim()) {
      return <div key={i} className="h-2" />
    }
    // Inline bold
    const parts = line.split(/\*\*(.*?)\*\*/g)
    return (
      <p key={i} className="text-sm text-slate-300 leading-relaxed">
        {parts.map((part, j) =>
          j % 2 === 1
            ? <strong key={j} className="text-slate-200 font-semibold">{part}</strong>
            : part
        )}
      </p>
    )
  })
}

export default function AnswerCard({ message }) {
  const [copied, setCopied] = useState(false)
  const [feedbackState, setFeedbackState] = useState(null) // 'helpful' | 'unhelpful'
  const isUnknown = message.question_type === 'UNKNOWN'
  const isEscalation = message.escalation_required
  const isInsufficient = message.question_type === 'INSUFFICIENT_EVIDENCE' || (message.confidence === 'Insufficient' && !isUnknown && !isEscalation)

  const handleCopy = () => {
    let text = message.content || ''
    if (message.sources && message.sources.length > 0) {
      text += '\n\nCitations:\n' + message.sources.map(s => `- ${s.document}, § ${s.section}, p. ${s.page} (${s.organization})`).join('\n')
    }
    navigator.clipboard.writeText(text)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  const handleExport = () => {
    const reportDate = new Date().toLocaleString()
    const reportText = `# Research Ethics Guidance Report

**Generated:** ${reportDate}  
**Classification:** ${message.question_type || 'SUPPORTED'}  
**Confidence Level:** ${message.confidence || 'N/A'}  
**Category:** ${message.category || 'General'}  
**Escalation Mandated:** ${message.escalation_required ? 'YES — Human Ethics Committee review required' : 'No'}

---

## Guidance Summary
${message.content}

---

## Verified Source Citations
${message.sources && message.sources.length > 0
  ? message.sources.map(s => `### ${s.document}
- **Section:** ${s.section || 'General'}
- **Page:** ${s.page || 'N/A'}
- **Institution:** ${s.organization || 'Provided Research Ethics Guideline'}
- **Excerpt:** "${s.excerpt || ''}"
`).join('\n')
  : 'No specific citations retrieved.'}

---
*Disclaimer: Generated by Research Ethics Guidance Assistant for informational and screening purposes. Not a substitute for formal Institutional Review Board (IRB) or Research Ethics Committee (REC) approval.*
`
    const blob = new Blob([reportText], { type: 'text/markdown;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `Ethics_Guidance_Report_${Date.now()}.md`
    a.click()
    URL.revokeObjectURL(url)
  }

  const handleFeedback = async (rating) => {
    if (feedbackState) return
    setFeedbackState(rating)
    try {
      await fetch('http://localhost:8000/feedback', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          message_id: String(message.id),
          question: message.userQuestion || '',
          rating: rating,
        }),
      })
    } catch {
      // Ignore network errors in feedback logging
    }
  }

  return (
    <div className="bubble-ai w-full animate-slide-up">
      <div className="p-5">
        {/* Header row */}
        <div className="flex items-center justify-between mb-4">
          <div className="flex items-center gap-2">
            {isEscalation ? (
              <AlertCircle size={13} className="text-amber-400" />
            ) : isInsufficient ? (
              <AlertCircle size={13} className="text-rose-400" />
            ) : isUnknown ? (
              <AlertCircle size={13} className="text-slate-400" />
            ) : (
              <Sparkles size={13} className="text-cyan-400" />
            )}
            <span
              className="text-xs font-bold tracking-widest uppercase"
              style={{
                color: isEscalation
                  ? '#fbbf24'
                  : isInsufficient
                  ? '#f87171'
                  : isUnknown
                  ? '#94a3b8'
                  : '#22d3ee',
              }}
            >
              {isEscalation
                ? 'HUMAN REVIEW REQUIRED'
                : isInsufficient
                ? 'INSUFFICIENT EVIDENCE'
                : isUnknown
                ? 'OUT OF SCOPE'
                : 'EVIDENCE GUIDANCE'}
            </span>
          </div>
          {message.confidence && !isUnknown && (
            <ConfidenceBadge confidence={message.confidence} />
          )}
        </div>

        {/* Escalation alert */}
        {isEscalation && (
          <EscalationAlert
            reason={message.escalation_reason}
            sources={message.sources}
            question={message.userQuestion}
            guidance={message.content}
          />
        )}

        {/* Answer text */}
        <div className="mt-3 space-y-0.5">
          {parseAnswer(message.content)}
        </div>

        {/* Insufficient evidence */}
        {isInsufficient && (
          <div className="mt-4 p-3.5 rounded-xl flex items-start gap-2.5"
            style={{ background: 'rgba(239,68,68,0.06)', border: '1px solid rgba(239,68,68,0.15)' }}>
            <div className="w-1.5 h-1.5 rounded-full bg-red-400 mt-1.5 flex-shrink-0" />
            <p className="text-xs text-slate-400">
              Please consult the appropriate research ethics authority or your institution's Ethics Committee / IRB / IEC.
            </p>
          </div>
        )}

        {/* Sources (only for non-escalation — escalation shows sources inline) */}
        {!isEscalation && message.sources && message.sources.length > 0 && (
          <div className="mt-5 pt-4 border-t border-white/5">
            <div className="text-xs font-semibold tracking-widest text-slate-500 uppercase mb-2.5">
              Verified Sources · {message.sources.length} {message.sources.length === 1 ? 'document' : 'documents'}
            </div>
            <div className="space-y-2">
              {message.sources.map((source, i) => (
                <SourceCard key={i} source={source} index={i} />
              ))}
            </div>
          </div>
        )}

        {/* Action Toolbar & Feedback Footer */}
        <div className="mt-4 pt-3.5 border-t border-white/5 flex items-center justify-between flex-wrap gap-2 text-xs">
          {/* Left: Category and metadata */}
          <div className="flex items-center gap-2">
            {message.category && (
              <span className="text-slate-500 text-[11px]">
                Domain: <span className="text-slate-400 font-medium">{message.category}</span>
              </span>
            )}
          </div>

          {/* Right: Actions */}
          <div className="flex items-center gap-2">
            {/* Copy button */}
            <button
              onClick={handleCopy}
              className="p-1.5 rounded-lg text-slate-400 hover:text-cyan-300 hover:bg-cyan-500/10 transition-colors flex items-center gap-1"
              title="Copy answer and citations"
            >
              {copied ? <Check size={12} className="text-green-400" /> : <Copy size={12} />}
              <span className="text-[11px]">{copied ? 'Copied' : 'Copy'}</span>
            </button>

            {/* Export Report button */}
            <button
              onClick={handleExport}
              className="p-1.5 rounded-lg text-slate-400 hover:text-cyan-300 hover:bg-cyan-500/10 transition-colors flex items-center gap-1"
              title="Download formal ethics guidance report (.md)"
            >
              <Download size={12} />
              <span className="text-[11px]">Export Report</span>
            </button>

            {/* Feedback Thumbs */}
            <div className="flex items-center gap-1 pl-2 border-l border-white/10">
              <button
                onClick={() => handleFeedback('helpful')}
                className={`p-1.5 rounded-lg transition-colors ${
                  feedbackState === 'helpful'
                    ? 'text-green-400 bg-green-500/20'
                    : 'text-slate-500 hover:text-slate-300 hover:bg-white/5'
                }`}
                title="Helpful guidance"
                disabled={feedbackState !== null}
              >
                <ThumbsUp size={12} />
              </button>
              <button
                onClick={() => handleFeedback('unhelpful')}
                className={`p-1.5 rounded-lg transition-colors ${
                  feedbackState === 'unhelpful'
                    ? 'text-amber-400 bg-amber-500/20'
                    : 'text-slate-500 hover:text-slate-300 hover:bg-white/5'
                }`}
                title="Unhelpful or incomplete"
                disabled={feedbackState !== null}
              >
                <ThumbsDown size={12} />
              </button>
              {feedbackState && (
                <span className="text-[10px] text-green-400/80 ml-1">Feedback saved</span>
              )}
            </div>
          </div>
        </div>
      </div>
    </div>
  )
}
